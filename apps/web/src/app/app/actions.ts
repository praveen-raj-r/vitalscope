"use server";

import { revalidatePath } from "next/cache";
import { createClient } from "@/lib/supabase/server";
import { createSiteSchema, parseOrigins } from "@/lib/sites";

export type CreateSiteState = {
  error?: string;
  site?: { name: string; siteKey: string };
};

export async function createSite(_prev: CreateSiteState, formData: FormData): Promise<CreateSiteState> {
  const parsed = createSiteSchema.safeParse({
    name: formData.get("name"),
    origins: formData.get("origins") ?? "",
  });
  if (!parsed.success) return { error: parsed.error.issues[0]?.message ?? "Invalid input" };

  const { origins, invalid } = parseOrigins(parsed.data.origins);
  if (invalid.length) return { error: `Invalid origin(s): ${invalid.join(", ")}` };
  if (origins.length === 0) return { error: "Add at least one allowed origin" };

  const supabase = await createClient();
  const { data: auth } = await supabase.auth.getUser();
  if (!auth.user) return { error: "Not signed in" };

  // site_key is generated by the DB default; RLS checks owner_id = auth.uid().
  const { data, error } = await supabase
    .from("sites")
    .insert({ owner_id: auth.user.id, name: parsed.data.name, allowed_origins: origins })
    .select("name, site_key")
    .single();
  if (error || !data) return { error: "Could not create site" };

  revalidatePath("/app");
  return { site: { name: data.name, siteKey: data.site_key } };
}
